// Country utilities for Mathathlon
// ISO 3166-1 alpha-2 codes to emoji flags and names

// Convert country code to emoji flag
// Works by converting each letter to its regional indicator symbol
export function getFlag(countryCode) {
  if (!countryCode || countryCode.length !== 2) return '';

  const code = countryCode.toUpperCase();
  const offset = 127397; // Regional indicator symbol offset

  return String.fromCodePoint(
    code.charCodeAt(0) + offset,
    code.charCodeAt(1) + offset
  );
}

